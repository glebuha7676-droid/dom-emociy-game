/* Пересобрать автономный HTML-экспорт после изменения исходников. */
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const bundle={
  css:read('styles.css')+'\n'+read('mobile.css'),
  scripts:['game-data.js','story-data.js','portrait-data.js','project-store.js','yard-layout.js','design-runtime.js','app.js'].map(read),
  house:'data:image/png;base64,'+fs.readFileSync(path.join(root,'assets/house-five-rooms-v1.png')).toString('base64'),
  homeBackground:'data:image/png;base64,'+fs.readFileSync(path.join(root,'assets/home-garden-v3.png')).toString('base64'),
  homePath:'data:image/png;base64,'+fs.readFileSync(path.join(root,'assets/home-path-v1.png')).toString('base64'),
  defaults:Object.fromEntries([
    ...['living','kitchen','kids','grandparents','parents'].map(id=>[`roomIcon:${id}`,`assets/room-icons/${id}-v1.png`]),
    ...['recognize','find','medal','daily'].map(id=>[`trainingIcon:${id}`,`assets/training-icons/${id}-v1.png`]),
    ...JSON.parse(read('assets/stories/manifest.json')).entries.map(entry=>[`story:${entry.id}`,entry.file]),
    ...['grandma','grandpa','mother','father','brother','sister'].map(id=>[`avatar:${id}`,`assets/avatars/${id}.png`]),
    ...JSON.parse(read('assets/characters/manifest.json')).entries.map(entry=>[`portrait:${entry.id}:${entry.emotion}`,entry.file])
  ].map(([slot,file])=>[slot,`data:image/${path.extname(file)==='.webp'?'webp':'png'};base64,`+fs.readFileSync(path.join(root,file)).toString('base64')]))
};
fs.writeFileSync(path.join(root,'export-bundle.js'),'/* Generated by tools/build-export.cjs. */\nwindow.EMOTION_EXPORT='+JSON.stringify(bundle)+';\n');
const ctx=require('node:vm').createContext({window:{}});require('node:vm').runInContext(read('project.js'),ctx,{timeout:1000});
const preset=ctx.window.EMOTION_PROJECT||{version:1,name:'Дом эмоций',theme:{},elements:{},assets:{},content:{},additions:{}};
const demo=require('./export-html.cjs')(bundle,preset);
fs.writeFileSync(path.join(root,'demo-one-file.html'),demo);
console.log('HTML export bundle ready.');
